import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const cssUrl = new URL("../apps/web/src/styles/tokens.css", import.meta.url);
const outputUrl = new URL("../apps/web/src/styles/tokens.generated.ts", import.meta.url);
const css = readFileSync(cssUrl, "utf8");
const source = css.match(/\/\* TOKEN_SOURCE_START \*\/([\s\S]*?)\/\* TOKEN_SOURCE_END \*\//)?.[1];
if (!source) throw new Error("Token source markers are missing from tokens.css");

const entries = [...source.matchAll(/(--omni-[a-z0-9-]+)\s*:\s*([^;]+);/g)]
  .map((match) => [match[1], match[2].trim()]);
if (entries.length === 0) throw new Error("No --omni-* tokens were found");
if (new Set(entries.map(([name]) => name)).size !== entries.length) {
  throw new Error("Token source contains duplicate --omni-* declarations");
}

const generated = `// Generated by scripts/export-web-tokens.mjs. Do not edit directly.\n` +
  `export const omniTokens = ${JSON.stringify(Object.fromEntries(entries), null, 2)} as const;\n\n` +
  `export type OmniTokenName = keyof typeof omniTokens;\n`;

if (process.argv.includes("--check")) {
  const current = readFileSync(outputUrl, "utf8");
  if (current !== generated) {
    process.stderr.write("Generated web tokens are stale. Run npm run tokens:generate.\n");
    process.exitCode = 1;
  }
} else {
  writeFileSync(fileURLToPath(outputUrl), generated);
}
